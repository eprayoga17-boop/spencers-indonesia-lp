// Vercel build step: bundle the starting content of data/ (pages, global, promos, redirects) into
// src/seed-data.js. On the first request after the first deploy it is copied into cloud storage
// (see ensureSeeded in src/storage.js); after that the admin edits live in Redis.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = {};
const add = (rel) => {
  const file = path.join(ROOT, rel);
  if (fs.existsSync(file)) files[rel.split(path.sep).join('/')] = fs.readFileSync(file, 'utf8');
};
for (const f of fs.readdirSync(path.join(ROOT, 'data', 'pages'))) if (f.endsWith('.json')) add(path.join('data', 'pages', f));
for (const f of ['global.json', 'promos.json', 'promos-draft.json', 'redirects.json']) add(path.join('data', f));
fs.writeFileSync(path.join(ROOT, 'src', 'seed-data.js'), `// Generated by scripts/build-seed.mjs. Do not edit.\nexport default ${JSON.stringify(files)};\n`);
console.log(`seed-data.js: ${Object.keys(files).length} files`);
