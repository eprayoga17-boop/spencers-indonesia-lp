// One-time (2026-10-15): storage that was seeded before the homepage existed gets the bundled data/pages/home.json
// (built by scripts/clone-homepage.mjs) and data/distributors.json. Existing data is never overwritten; a kv claim
// keeps it to one run.
import { getPage, createPage } from './store.js';
import { kv } from './storage.js';
import { updateDistributors, getDistributors } from './distributors.js';

const KEY = 'migration:homepage-v1';

async function addHomepage() {
  let files;
  try {
    files = (await import('./seed-data.js')).default; // generated by `npm run vercel-build`
  } catch {
    return 'no seed';
  }
  const out = [];
  const dist = files['data/distributors.json'];
  if (dist && !(await getDistributors({ fresh: true })).length) {
    await updateDistributors(() => JSON.parse(dist).items || []);
    out.push('distributors');
  }
  const text = files['data/pages/home.json'];
  if (!text || (await getPage('home'))) return out.join(', ') || 'skip';
  const { updatedAt, updatedBy, ...page } = JSON.parse(text);
  await createPage('home', page, updatedBy || 'migrasi otomatis');
  return [...out, 'homepage'].join(', ');
}

let running = null;
export function ensureHomepage() {
  running ||= (async () => {
    if (!(await kv.claim(KEY, { at: Date.now() }, 10 * 365 * 864e5))) return;
    try {
      console.log(`migration homepage-v1: ${await addHomepage()}`);
    } catch (e) {
      await kv.del(KEY); // try again on the next start
      throw e;
    }
  })().catch((e) => { running = null; console.error('migration homepage-v1 failed', e); });
  return running;
}
